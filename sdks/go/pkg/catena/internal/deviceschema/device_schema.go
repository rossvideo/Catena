// A Patterns represents a $defs entry in the schema with a const name.
type Pattern struct {
	Def   string
	Const string
}

// Patterns is the list of $defs entries to be written to schema_generated.go.
var Patterns = []Pattern{
	{Def: "fqoid", Const: "fqoidPattern"},
	{Def: "language_code", Const: "languageCodePattern"},
}

// Definiton represents one reusable definition under the YAML $defs key.
type Definition struct {
	Pattern string `yaml:"pattern"`
}

// Schema represents the top-level structure of the device.yaml schema.
type Schema struct {
	Defs map[string]Definition `yaml:"$defs"`
}

// Generate renders schema_generated.go from the patterns in schemaPath.
func Generate(schemaPath string) ([]byte, error) {
	patternsMap, err := ReadPatterns(schemaPath)
	if err != nil {
		return nil, err
	}
	return render(patternsMap)
}

// ReadPatterns reads the schema and returns the regex for each $defs entry
func ReadPatterns(path string) (map[string]string, error) {
	deviceYamlFile, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var schemaDoc Schema
	if err := yaml.Unmarshal(deviceYamlFile, &schemaDoc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}

	out := make(map[string]string, len(Patterns))
	for _, pattern := range Patterns {
		def, ok := schemaDoc.Defs[pattern.Def]
		if !ok {
			return nil, fmt.Errorf("%s: missing $defs/%s", path, pattern.Def)
		}

		if def.Pattern == "" {
			return nil, fmt.Errorf("%s: $defs/%s pattern is empty", path, pattern.Def)
		}
		out[pattern.Def] = def.Pattern
	}

	return out, nil
}

func render(patternsMap map[string]string) ([]byte, error) {
	var b strings.Builder
	b.WriteString(fileHeader)

	b.WriteString("package catena\n\nconst (\n")
	for _, pattern := range Patterns {

		if !token.IsIdentifier(pattern.Const) {
			return nil, fmt.Errorf("invalid const name %q", pattern.Const)
		}

		regexPattern, ok := patternsMap[pattern.Def]
		if !ok {
			return nil, fmt.Errorf("missing pattern for $defs/%s", pattern.Def)
		}

		fmt.Fprintf(&b, "\t%s = `%s`\n", pattern.Const, regexPattern)
	}
	b.WriteString(")\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w\n%s", err, b.String())
	}
	return src, nil
}
