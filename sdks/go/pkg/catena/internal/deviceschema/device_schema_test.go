func writeSchema(t *testing.T, contents string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "device.yaml")
	if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestGenerate(t *testing.T) {

	t.Run("valid generation", func(t *testing.T) {
		path := writeSchema(t, `
$defs:
  fqoid:
    pattern: "^fq$"
  language_code:
    pattern: "^[a-z]{2}$"
`)

		src, err := Generate(path)
		if err != nil {
			t.Fatal(err)
		}
		again, err := Generate(path)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(src, again) {
			t.Fatal("Generate output is not deterministic")
		}

		formatted, err := format.Source(src)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(src, formatted) {
			t.Fatal("Generate output is not gofmt-clean")
		}
		text := string(src)
		if !strings.Contains(text, "Code generated by schemagen; DO NOT EDIT.") {
			t.Fatal("generated file missing DO NOT EDIT marker")
		}
	})

	t.Run("invalid generation", func(t *testing.T) {
		path := writeSchema(t, `
$defs:
  language_code:
    pattern: "^[a-z]{2}$"
`)
		_, err := Generate(path)
		if err == nil {
			t.Fatalf("Generate should return an error for missing $defs/fqoid: %v", err)
		}
	})

}

func TestReadPatterns(t *testing.T) {
	t.Run("reads generated patterns", func(t *testing.T) {
		path := writeSchema(t, `
$defs:
  fqoid:
    pattern: '^fq$'
  language_code:
    pattern: "^[a-z]{2}$"
`)
		got, err := ReadPatterns(path)
		if err != nil {
			t.Fatal(err)
		}

		if got["fqoid"] != "^fq$" {
			t.Fatalf("fqoid = %q, want %q", got["fqoid"], "^fq$")
		}

		if got["language_code"] != "^[a-z]{2}$" {
			t.Fatalf("language_code = %q, want %q", got["language_code"], "^[a-z]{2}$")
		}

	})

	t.Run("missing file", func(t *testing.T) {
		_, err := ReadPatterns(filepath.Join(t.TempDir(), "missing.yaml"))
		if err == nil || !os.IsNotExist(err) {
			t.Fatalf("ReadPatterns() error = %v, want a missing-file error", err)
		}
	})

	t.Run("invalid yaml", func(t *testing.T) {
		path := writeSchema(t, ":\n some invalid yaml")
		_, err := ReadPatterns(path)
		if err == nil || !strings.Contains(err.Error(), "yaml:") {
			t.Fatalf("ReadPatterns() error = %v, want a yaml error", err)
		}
	})

	t.Run("missing def", func(t *testing.T) {
		path := writeSchema(t, `
$defs:
  fqoid:
    pattern: "^fq$"
`)
		_, err := ReadPatterns(path)
		if err == nil || !strings.Contains(err.Error(), "missing $defs/language_code") {
			t.Fatalf("ReadPatterns() error = %v, want missing $defs/language_code", err)
		}
	})

	t.Run("empty pattern", func(t *testing.T) {
		path := writeSchema(t, `
$defs:
  fqoid:
    pattern: ""
  language_code:
    pattern: "^lc$"
`)
		_, err := ReadPatterns(path)
		if err == nil || !strings.Contains(err.Error(), "$defs/fqoid pattern is empty") {
			t.Fatalf("ReadPatterns() error = %v, want an empty pattern", err)
		}
	})
}

func TestRender(t *testing.T) {
	t.Run("invalid const name", func(t *testing.T) {
		original := Patterns
		Patterns = []Pattern{
			{Def: "fqoid", Const: "not-valid"},
			{Def: "language_code", Const: "languageCodePattern"},
		}
		t.Cleanup(func() { Patterns = original })

		_, err := render(map[string]string{
			"fqoid":         "^fq$",
			"language_code": "^[a-z]{2}$",
		})
		if err == nil || !strings.Contains(err.Error(), `invalid const name "not-valid"`) {
			t.Fatalf("render() error = %v, want an invalid const name", err)
		}
	})

	t.Run("missing pattern", func(t *testing.T) {
		_, err := render(map[string]string{
			"language_code": "^[a-z]{2}$",
		})
		if err == nil || !strings.Contains(err.Error(), "missing pattern for $defs/fqoid") {
			t.Fatalf("render() error = %v, want a missing pattern", err)
		}
	})

	t.Run("pattern breaks go syntax", func(t *testing.T) {
		_, err := render(map[string]string{
			"fqoid":         "has ` backtick",
			"language_code": "^[a-z]{2}$",
		})
		if err == nil || !strings.Contains(err.Error(), "format generated source") {
			t.Fatalf("render() error = %v, want a format error", err)
		}
	})
}

// TestSchemaGeneratedMatchesDeviceYAML fails when schema_generated.go drifts
// from smpte/interface/schema/device.yaml. It compares the generated bytes
// to the previously generated file's bytes and validates that they match.
// A missing smpte submodule skips the test locally but fails when CI is set
// GitHub Actions sets CI=true
func TestSchemaGeneratedMatchesDeviceYAML(t *testing.T) {
	const (
		schemaPath    = "../../../../../../smpte/interface/schema/device.yaml"
		generatedPath = "../../schema_generated.go"
	)

	if _, err := os.Stat(schemaPath); err != nil {
		if !os.IsNotExist(err) {
			t.Fatal(err)
		}

		if os.Getenv("CI") != "" {
			t.Fatalf("%s not found; CI requires the smpte submodule", schemaPath)
		}

		t.Skipf("%s not found; leaving generated file unchecked", schemaPath)
	}

	generatedBytes, err := Generate(schemaPath)
	if err != nil {
		t.Fatal(err)
	}
	repeatedGenerationBytes, err := Generate(schemaPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(generatedBytes, repeatedGenerationBytes) {
		t.Fatal("Generate output is not deterministic")
	}

	generatedSrcFileBytes, err := os.ReadFile(generatedPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(generatedBytes, generatedSrcFileBytes) {
		t.Fatalf("schema_generated.go is out of sync with %s\nregenerate with: go generate ./pkg/catena/", schemaPath)
	}
}
